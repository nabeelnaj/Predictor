import { useRef, useId } from 'react';
import { Download, Printer, RotateCcw } from 'lucide-react';

interface CalculatorLayoutProps {
  title: string;
  description: string;
  icon: React.ReactNode;
  accentColor: string;
  children: React.ReactNode;
  onReset: () => void;
}

export default function CalculatorLayout({
  title,
  description,
  icon,
  accentColor,
  children,
  onReset,
}: CalculatorLayoutProps) {
  const resultRef = useRef<HTMLDivElement>(null);

  function handlePrint() {
    window.print();
  }

  function handleDownload() {
    const el = resultRef.current;
    if (!el) return;

    const text = el.innerText;
    const blob = new Blob([`${title}\n${'='.repeat(title.length)}\n\n${text}\n\nGenerated by InvestPredictor`], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${title.replace(/\s+/g, '_').toLowerCase()}_results.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="print-area">
      <div className="mb-6 no-print">
        <div className="flex items-center gap-2 text-xs text-gray-500 mb-2">
          <span>Calculators</span>
          <span>/</span>
          <span className="text-white">{title}</span>
        </div>
        <div className="flex items-center gap-3">
          <div
            className="w-10 h-10 rounded-xl flex items-center justify-center shrink-0"
            style={{ background: `${accentColor}15`, color: accentColor }}
          >
            {icon}
          </div>
          <div>
            <h1 className="text-xl sm:text-2xl font-bold text-white">{title}</h1>
            <p className="text-sm text-gray-500">{description}</p>
          </div>
        </div>
      </div>

      <div ref={resultRef} className="grid lg:grid-cols-5 gap-6">
        {children}
      </div>

      <div className="mt-6 flex items-center gap-3 no-print">
        <button
          onClick={handleDownload}
          className="flex items-center gap-2 px-4 py-2 text-sm font-medium text-white bg-blue-600 hover:bg-blue-700 rounded-lg transition-colors"
        >
          <Download size={14} /> Download Results
        </button>
        <button
          onClick={handlePrint}
          className="flex items-center gap-2 px-4 py-2 text-sm font-medium text-gray-300 bg-gray-800 hover:bg-gray-700 rounded-lg transition-colors"
        >
          <Printer size={14} /> Print
        </button>
        <button
          onClick={onReset}
          className="flex items-center gap-2 px-4 py-2 text-sm font-medium text-gray-400 hover:text-white transition-colors ml-auto"
        >
          <RotateCcw size={14} /> Reset
        </button>
      </div>
    </div>
  );
}

