interface AreaChartProps {
  data: number[];
  labels: string[];
  color?: string;
  height?: number;
  title?: string;
}

export function AreaChart({ data, labels, color = '#3b82f6', height = 200, title }: AreaChartProps) {
  const gradId = useId();
  if (data.length === 0) return null;

  const width = 600;
  const padding = { top: 20, right: 20, bottom: 30, left: 50 };
  const chartW = width - padding.left - padding.right;
  const chartH = height - padding.top - padding.bottom;

  const maxVal = Math.max(...data, 1);
  const minVal = Math.min(...data, 0);
  const range = maxVal - minVal || 1;

  const points = data.map((d, i) => {
    const x = padding.left + (i / Math.max(data.length - 1, 1)) * chartW;
    const y = padding.top + chartH - ((d - minVal) / range) * chartH;
    return { x, y };
  });

  const pathD = points.map((p, i) => `${i === 0 ? 'M' : 'L'} ${p.x} ${p.y}`).join(' ');
  const areaD = `${pathD} L ${points[points.length - 1].x} ${padding.top + chartH} L ${points[0].x} ${padding.top + chartH} Z`;

  // Y-axis labels (4 ticks)
  const yTicks = Array.from({ length: 5 }, (_, i) => minVal + (range * i) / 4);
  // X-axis labels (up to 6)
  const xTickIndices = Array.from({ length: Math.min(6, data.length) }, (_, i) =>
    Math.floor((i * (data.length - 1)) / 5)
  );

  return (
    <div className="w-full">
      {title && <p className="text-xs font-medium text-gray-400 mb-2">{title}</p>}
      <svg viewBox={`0 0 ${width} ${height}`} className="w-full" style={{ height: 'auto' }}>
        <defs>
          <linearGradient id={gradId} x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stopColor={color} stopOpacity="0.35" />
            <stop offset="100%" stopColor={color} stopOpacity="0.02" />
          </linearGradient>
        </defs>

        {/* Grid lines */}
        {yTicks.map((t, i) => {
          const y = padding.top + chartH - ((t - minVal) / range) * chartH;
          return (
            <g key={i}>
              <line x1={padding.left} y1={y} x2={width - padding.right} y2={y} stroke="#1f2937" strokeWidth="0.5" />
              <text x={padding.left - 8} y={y + 3} textAnchor="end" fill="#6b7280" fontSize="9">
                {formatCompact(t)}
              </text>
            </g>
          );
        })}

        {/* Area + Line */}
        <path d={areaD} fill={`url(#${gradId})`} />
        <path d={pathD} fill="none" stroke={color} strokeWidth="2" strokeLinejoin="round" />

        {/* X-axis labels */}
        {xTickIndices.map((idx, i) => {
          const p = points[idx];
          return (
            <text key={i} x={p.x} y={height - 8} textAnchor="middle" fill="#6b7280" fontSize="9">
              {labels[idx]}
            </text>
          );
        })}
      </svg>
    </div>
  );
}

interface DonutChartProps {
  segments: { label: string; value: number; color: string }[];
  centerLabel?: string;
  centerValue?: string;
  size?: number;
}

export function DonutChart({ segments, centerLabel, centerValue, size = 180 }: DonutChartProps) {
  const total = segments.reduce((sum, s) => sum + s.value, 0);
  if (total === 0) return null;

  const radius = size / 2 - 20;
  const innerRadius = radius * 0.62;
  const cx = size / 2;
  const cy = size / 2;

  let currentAngle = -Math.PI / 2;

  const arcs = segments.map(s => {
    const angle = (s.value / total) * Math.PI * 2;
    const startAngle = currentAngle;
    const endAngle = currentAngle + angle;
    currentAngle = endAngle;

    const x1 = cx + radius * Math.cos(startAngle);
    const y1 = cy + radius * Math.sin(startAngle);
    const x2 = cx + radius * Math.cos(endAngle);
    const y2 = cy + radius * Math.sin(endAngle);
    const x3 = cx + innerRadius * Math.cos(endAngle);
    const y3 = cy + innerRadius * Math.sin(endAngle);
    const x4 = cx + innerRadius * Math.cos(startAngle);
    const y4 = cy + innerRadius * Math.sin(startAngle);

    const largeArc = angle > Math.PI ? 1 : 0;

    return {
      ...s,
      path: `M ${x1} ${y1} A ${radius} ${radius} 0 ${largeArc} 1 ${x2} ${y2} L ${x3} ${y3} A ${innerRadius} ${innerRadius} 0 ${largeArc} 0 ${x4} ${y4} Z`,
      pct: (s.value / total) * 100,
    };
  });

  return (
    <div className="flex flex-col items-center gap-4">
      <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`}>
        {arcs.map((a, i) => (
          <path key={i} d={a.path} fill={a.color} />
        ))}
        {centerValue && (
          <text x={cx} y={cy - 2} textAnchor="middle" fill="#fff" fontSize="14" fontWeight="700">
            {centerValue}
          </text>
        )}
        {centerLabel && (
          <text x={cx} y={cy + 14} textAnchor="middle" fill="#9ca3af" fontSize="9">
            {centerLabel}
          </text>
        )}
      </svg>
      <div className="space-y-2 w-full">
        {arcs.map((a, i) => (
          <div key={i} className="flex items-center justify-between text-xs">
            <div className="flex items-center gap-2">
              <div className="w-2.5 h-2.5 rounded-sm" style={{ background: a.color }} />
              <span className="text-gray-400">{a.label}</span>
            </div>
            <span className="text-white font-semibold">{formatCurrency(a.value)} ({a.pct.toFixed(1)}%)</span>
          </div>
        ))}
      </div>
    </div>
  );
}

interface BarChartProps {
  data: { label: string; value: number; color?: string }[];
  height?: number;
  title?: string;
  defaultColor?: string;
}

export function BarChart({ data, height = 200, title, defaultColor = '#3b82f6' }: BarChartProps) {
  if (data.length === 0) return null;
  const maxVal = Math.max(...data.map(d => Math.abs(d.value)), 1);

  return (
    <div className="w-full">
      {title && <p className="text-xs font-medium text-gray-400 mb-2">{title}</p>}
      <div className="flex items-end gap-1.5" style={{ height }}>
        {data.map((d, i) => {
          const h = (Math.abs(d.value) / maxVal) * (height - 30);
          return (
            <div key={i} className="flex-1 flex flex-col items-center gap-1 group">
              <span className="text-[9px] text-gray-500 opacity-0 group-hover:opacity-100 transition-opacity">
                {formatCompact(d.value)}
              </span>
              <div
                className="w-full rounded-t transition-all hover:opacity-80"
                style={{
                  height: `${Math.max(h, 2)}px`,
                  background: d.color ?? defaultColor,
                }}
              />
              <span className="text-[9px] text-gray-500 text-center truncate w-full">{d.label}</span>
            </div>
          );
        })}
      </div>
    </div>
  );
}

